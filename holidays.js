// 返回某天的类型：{ kind: 'work' | 'weekend' | 'holiday', name }
window.dayKind = function (key, override) {
  if (override === 'work') return { kind: 'work', name: '' };
  if (override === 'off') return { kind: 'weekend', name: '休息' };
  const y = Number(key.slice(0, 4));
  const t = window.HOLIDAYS[y];
  if (t) {
    if (t.off[key]) return { kind: 'holiday', name: t.off[key] };
    if (t.work.includes(key)) return { kind: 'work', name: '调休' };
  }
  const [yy, mm, dd] = key.split('-').map(Number);
  const wd = new Date(yy, mm - 1, dd).getDay();
  return wd === 0 || wd === 6 ? { kind: 'weekend', name: '' } : { kind: 'work', name: '' };
};
